function Get-UiLang {
    $c = (Get-UICulture).TwoLetterISOLanguageName
    if ($Strings.ContainsKey($c)) { return $c }
    return 'en'
}

function Get-Text($key) {
    $lang = Get-UiLang
    $v = $Strings[$lang][$key]
    if (-not $v) { $v = $Strings['en'][$key] }
    return $v
}
